-- Match the browser's completed-stage rule: a zero-value stage is cleared
-- once a charge exists, while an uncharged stage is not marked as paid.
CREATE OR REPLACE FUNCTION public.ledger_case_stage_status(p_case_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_result jsonb := '{}'::jsonb;
  v_stage text;
  v_due numeric;
  v_has_charge boolean;
  v_direct_received numeric;
  v_general_pool numeric;
  v_general_applied numeric;
  v_stage_received numeric;
BEGIN
  SELECT COALESCE(SUM(e.amount_received), 0)
    INTO v_general_pool
  FROM public.ledger_entries e
  WHERE e.case_id = p_case_id AND e.entry_type = 'receiving'
    AND e.stage IS NULL AND e.linked_entry_id IS NULL AND e.voided_at IS NULL;

  FOREACH v_stage IN ARRAY ARRAY['S1','S2','S3','S4'] LOOP
    SELECT COALESCE(SUM(e.amount_due), 0), COUNT(*) > 0
      INTO v_due, v_has_charge
    FROM public.ledger_entries e
    WHERE e.case_id = p_case_id AND e.entry_type = 'charge'
      AND e.stage = v_stage AND e.voided_at IS NULL;

    SELECT COALESCE(SUM(r.amount_received), 0)
      INTO v_direct_received
    FROM public.ledger_entries r
    WHERE r.case_id = p_case_id AND r.entry_type = 'receiving'
      AND r.voided_at IS NULL
      AND ((r.linked_entry_id IS NULL AND r.stage = v_stage)
        OR r.linked_entry_id IN (
          SELECT c.id FROM public.ledger_entries c
          WHERE c.case_id = p_case_id AND c.entry_type = 'charge'
            AND c.stage = v_stage AND c.voided_at IS NULL
        ));

    v_general_applied := LEAST(v_general_pool, GREATEST(v_due - v_direct_received, 0));
    v_general_pool := GREATEST(v_general_pool - v_general_applied, 0);
    v_stage_received := v_direct_received + v_general_applied;

    v_result := v_result || jsonb_build_object(v_stage, jsonb_build_object(
      'amount_due', v_due,
      'amount_received', v_stage_received,
      'outstanding', GREATEST(v_due - v_stage_received, 0),
      'paid', v_has_charge AND (v_due = 0 OR v_stage_received >= v_due)
    ));
  END LOOP;
  RETURN v_result;
END;
$$;

-- Number only folders generated by the app. Existing labels are left intact;
-- the sequence begins at one greater than the largest numeric folder present.
CREATE SEQUENCE IF NOT EXISTS public.case_folder_no_seq;
DO $$
DECLARE
  v_next bigint;
BEGIN
  SELECT COALESCE(MAX(folder_no::bigint), 0) + 1
    INTO v_next
  FROM public.cases
  WHERE folder_no ~ '^[0-9]+$';
  PERFORM setval('public.case_folder_no_seq', GREATEST(v_next, 1), false);
END;
$$;

CREATE OR REPLACE FUNCTION public.assign_case_folder_no()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_number bigint;
BEGIN
  IF NEW.folder_no IS NULL OR btrim(NEW.folder_no) = '' THEN
    v_number := nextval('public.case_folder_no_seq');
    NEW.folder_no := CASE WHEN v_number < 1000
      THEN lpad(v_number::text, 3, '0')
      ELSE v_number::text END;
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.assign_case_folder_no() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS trg_cases_assign_folder_no ON public.cases;
CREATE TRIGGER trg_cases_assign_folder_no
  BEFORE INSERT ON public.cases
  FOR EACH ROW EXECUTE FUNCTION public.assign_case_folder_no();

-- Start at any valid stage. Thereafter require paid, contiguous forward stages.
-- Voids are allowed as audit corrections; they can make later stages appear
-- outstanding and block new forward progress until corrected.
CREATE OR REPLACE FUNCTION public.enforce_ledger_stage_gate()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_case_id uuid;
  v_stage text;
  v_order int;
  v_start_order int;
  v_previous text;
  v_status jsonb;
  v_new_order int;
  v_old_order int;
BEGIN
  IF TG_OP = 'UPDATE' AND OLD.case_id IS DISTINCT FROM NEW.case_id THEN
    RAISE EXCEPTION 'Ledger entries cannot be reassigned between cases; void and repost the entry';
  END IF;

  -- A soft void is a correction action and must remain possible even where it
  -- reveals a broken/voided earlier stage in the case history.
  IF TG_OP = 'UPDATE' AND OLD.voided_at IS NULL AND NEW.voided_at IS NOT NULL THEN
    RETURN NULL;
  END IF;

  IF TG_OP = 'DELETE' THEN
    v_case_id := OLD.case_id;
  ELSE
    v_case_id := NEW.case_id;
  END IF;

  IF v_case_id IS NOT NULL THEN
    IF TG_OP = 'UPDATE' AND NEW.entry_type = 'charge' AND NEW.voided_at IS NULL THEN
      v_new_order := array_position(ARRAY['S1','S2','S3','S4'], NEW.stage);
      v_old_order := array_position(ARRAY['S1','S2','S3','S4'], OLD.stage);
      IF v_new_order IS NOT NULL AND v_old_order IS NOT NULL AND v_new_order < v_old_order THEN
        RAISE EXCEPTION 'Case stages can only move forward';
      END IF;
    END IF;

    SELECT MIN(array_position(ARRAY['S1','S2','S3','S4'], e.stage))
      INTO v_start_order
    FROM public.ledger_entries e
    WHERE e.case_id = v_case_id
      AND e.entry_type = 'charge'
      AND e.voided_at IS NULL
      AND e.stage IN ('S1','S2','S3','S4');

    v_status := public.ledger_case_stage_status(v_case_id);
    FOR v_stage IN
      SELECT DISTINCT e.stage
      FROM public.ledger_entries e
      WHERE e.case_id = v_case_id
        AND e.entry_type = 'charge'
        AND e.voided_at IS NULL
        AND e.stage IN ('S1','S2','S3','S4')
      ORDER BY e.stage
    LOOP
      v_order := array_position(ARRAY['S1','S2','S3','S4'], v_stage);
      IF v_order > COALESCE(v_start_order, v_order) THEN
        v_previous := 'S' || (v_order - 1)::text;
        IF COALESCE((v_status -> v_previous ->> 'paid')::boolean, false) IS NOT TRUE THEN
          RAISE EXCEPTION 'Stage % must be fully cleared before stage % can remain active', v_previous, v_stage;
        END IF;
      END IF;
    END LOOP;

    -- Reject a newly inserted or changed active charge that goes behind the
    -- highest active case stage, even if a previous charge was later voided.
    IF TG_OP <> 'DELETE' AND NEW.entry_type = 'charge' AND NEW.voided_at IS NULL THEN
      v_new_order := array_position(ARRAY['S1','S2','S3','S4'], NEW.stage);
      IF v_new_order IS NOT NULL AND EXISTS (
        SELECT 1 FROM public.ledger_entries e
        WHERE e.case_id = v_case_id AND e.entry_type = 'charge'
          AND e.voided_at IS NULL AND e.stage IN ('S1','S2','S3','S4')
          AND e.id IS DISTINCT FROM NEW.id
          AND array_position(ARRAY['S1','S2','S3','S4'], e.stage) > v_new_order
      ) THEN
        RAISE EXCEPTION 'Case stages can only move forward';
      END IF;
    END IF;
  END IF;
  RETURN NULL;
END;
$$;

-- Private, authenticated-only evidence storage. Staff already use the
-- authenticated role for Ledger tables; public/anonymous access is not granted.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('ledger-evidence', 'ledger-evidence', false, 5242880,
        ARRAY['image/jpeg','image/png','image/webp'])
ON CONFLICT (id) DO UPDATE SET
  public = false,
  file_size_limit = 5242880,
  allowed_mime_types = ARRAY['image/jpeg','image/png','image/webp'];

DROP POLICY IF EXISTS "ledger_evidence_authenticated_read" ON storage.objects;
DROP POLICY IF EXISTS "ledger_evidence_authenticated_insert" ON storage.objects;
DROP POLICY IF EXISTS "ledger_evidence_authenticated_update" ON storage.objects;
DROP POLICY IF EXISTS "ledger_evidence_authenticated_delete" ON storage.objects;
CREATE POLICY "ledger_evidence_authenticated_read" ON storage.objects
  FOR SELECT TO authenticated USING (bucket_id = 'ledger-evidence');
CREATE POLICY "ledger_evidence_authenticated_insert" ON storage.objects
  FOR INSERT TO authenticated WITH CHECK (bucket_id = 'ledger-evidence');
CREATE POLICY "ledger_evidence_authenticated_update" ON storage.objects
  FOR UPDATE TO authenticated USING (bucket_id = 'ledger-evidence')
  WITH CHECK (bucket_id = 'ledger-evidence');
CREATE POLICY "ledger_evidence_authenticated_delete" ON storage.objects
  FOR DELETE TO authenticated USING (bucket_id = 'ledger-evidence');

COMMIT;
