-- Client codes identify a client within a series. Keep unassigned clients
-- unique within their own NULL-series group.
ALTER TABLE public.clients DROP CONSTRAINT IF EXISTS clients_client_code_key;
CREATE UNIQUE INDEX IF NOT EXISTS clients_series_code_unique
  ON public.clients (series_id, upper(btrim(client_code)))
  WHERE series_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS clients_unassigned_code_unique
  ON public.clients (upper(btrim(client_code)))
  WHERE series_id IS NULL;

